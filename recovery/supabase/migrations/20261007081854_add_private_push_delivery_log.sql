create table if not exists public.private_push_delivery_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  chat_id uuid,
  target_user_id uuid,
  subscription_id bigint,
  status text not null,
  http_status integer,
  error_message text
);
alter table public.private_push_delivery_log enable row level security;
